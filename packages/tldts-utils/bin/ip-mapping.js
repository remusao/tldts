#!/usr/bin/env node

'use strict';

// Writes packages/tldts-core/src/ip-mapping.ts: the non-ASCII code points that
// the host parser of browsers (UTS #46 mapping, as the WHATWG URL standard
// uses it) turns into something that matters for IP detection. That is, code
// points deleted from a host, mapped to '.', or mapped to digits, 'a'-'f' and
// 'x' only ("１" -> "1", "⑩" -> "10"). Any other code point keeps a label from
// being a number. The table comes from the URL parser of the running Node.js,
// one code point at a time: re-run this script with a Node.js release whose
// Unicode version is newer to update it.

const fs = require('fs');
const path = require('path');

const out = path.resolve(__dirname, '../../tldts-core/src/ip-mapping.ts');

// cp -> its mapping ('' when deleted), for the code points that matter.
const mapping = [];
for (let cp = 0x80; cp <= 0x10ffff; cp += 1) {
  if (cp >= 0xd800 && cp <= 0xdfff) {
    continue; // surrogates
  }
  let hostname;
  try {
    hostname = new URL(`http://q${String.fromCodePoint(cp)}q.test/`).hostname;
  } catch {
    continue; // not allowed in a host
  }
  if (hostname === 'q.q.test') {
    mapping.push([cp, '.']);
  } else {
    const match = /^q([0-9a-fx]*)q\.test$/.exec(hostname);
    // A number is decimal digits, or "0x" then hexadecimal digits: a mapping
    // with an 'x' anywhere but right after a leading '0' ("℻" -> "fax") can
    // never be part of one, like any other code point.
    if (match !== null && !/^(?!0x).+x/.test(match[1])) {
      mapping.push([cp, match[1]]);
    }
  }
}

// Ranges of consecutive code points whose mappings follow each other: the same
// empty mapping (deleted), consecutive characters, or consecutive decimal
// numbers. Each range is [first, last, value], where value is 0 for deleted, the
// code of the character for one character (below 128), 1000 + the number for a
// decimal number (10 to 50), and the two character codes as `c1 << 8 | c2` for
// two hexadecimal letters ("da", 0x6461).
const valueOf = (s) => {
  if (s === '') return 0;
  if (s.length === 1) return s.charCodeAt(0);
  if (/^[1-9][0-9]$/.test(s)) return 1000 + Number(s);
  if (/^[a-f]{2}$/.test(s)) return (s.charCodeAt(0) << 8) | s.charCodeAt(1);
  throw new Error(`a mapping to "${s}" is not supported`);
};
const kind = (v) => (v === 0 ? 0 : v < 128 ? 1 : v < 2000 ? 2 : 3);
const ranges = [];
for (const [cp, s] of mapping) {
  const value = valueOf(s);
  const last = ranges[ranges.length - 1];
  if (
    last !== undefined &&
    last[1] === cp - 1 &&
    kind(last[2]) === kind(value) &&
    kind(value) !== 3 &&
    value === (kind(value) === 0 ? 0 : last[2] + (cp - last[0]))
  ) {
    last[1] = cp;
  } else {
    ranges.push([cp, cp, value]);
  }
}

// Blocks of 256 code points below U+10000 holding any of them, one bit each,
// so that most letters (Cyrillic, CJK, ...) are told apart at once.
const blocks = new Array(8).fill(0);
for (const [cp] of mapping) {
  if (cp < 0x10000) {
    blocks[cp >> 13] |= 1 << ((cp >> 8) & 31);
  }
}

fs.writeFileSync(
  out,
  [
    `// Auto-generated by packages/tldts-utils/bin/ip-mapping.js (Node.js ${process.version}, Unicode ${process.versions.unicode}). Do not edit.`,
    '//',
    '// Non-ASCII code points that the host parser of browsers deletes, or maps to',
    "// '.', or to digits, 'a'-'f' and 'x' only, as ranges: code points",
    '// `ipMappingFirst[k]` to `ipMappingLast[k]` map, with `value = ipMappingValue[k]`',
    '// and `offset` the position in the range: to nothing if `value` is 0, to the',
    '// character `value + offset` if `value` is below 128, to the decimal number',
    '// `value - 1000 + offset` if `value` is below 2000, and else to the two',
    '// characters `value >> 8` and `value & 255`.',
    `export const ipMappingFirst = /*#__PURE__*/ new Uint32Array([${ranges.map((r) => r[0]).join(',')}]);`,
    `export const ipMappingLast = /*#__PURE__*/ new Uint32Array([${ranges.map((r) => r[1]).join(',')}]);`,
    `export const ipMappingValue = /*#__PURE__*/ new Uint16Array([${ranges.map((r) => r[2]).join(',')}]);`,
    '// Bit `(cp >> 8) & 31` of `ipMappingBlocks[cp >> 13]` is set when the block of',
    '// 256 code points holding `cp` (below U+10000) holds any of them.',
    `export const ipMappingBlocks = /*#__PURE__*/ new Uint32Array([${blocks.map((b) => b >>> 0).join(',')}]);`,
    '',
  ].join('\n'),
);
console.log(
  `${mapping.length} code points in ${ranges.length} ranges -> ${out}`,
);
